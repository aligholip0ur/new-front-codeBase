export const maskString = (value: string): string => {
  // اگر طول رشته ۴ کاراکتر یا کمتر بود
  if (value.length <= 4) {
    // به اندازه طول رشته، * برمی‌گردونیم
    return '*'.repeat(value.length);
  }

  // گرفتن ۲ کاراکتر اول رشته
  const start = value.slice(0, 2);

  // گرفتن ۲ کاراکتر آخر رشته
  const end = value.slice(-2);

  // محاسبه تعداد کاراکترهای وسط و جایگزینی آن‌ها با *
  const middle = '*'.repeat(value.length - 4);

  // ترکیب ۲ کاراکتر اول + *های وسط + ۲ کاراکتر آخر
  return `${start}${middle}${end}`;
};

